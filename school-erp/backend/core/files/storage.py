"""Pluggable object storage with short-lived signed URLs (P1-22).

Two drivers are provided:

* ``local`` writes under ``STORAGE_DIR`` and signs a download URL with an
  HMAC over the object key and expiry. It is the default for development and
  for hosts without object storage.
* ``s3`` talks to any S3-compatible endpoint (MinIO, R2, AWS) using a
  SigV4-presigned URL. No boto3 dependency is needed; signatures are generated
  with the standard library and requests are made with httpx.

Keys are generated by the service and never come from user input, but the
local driver still refuses absolute paths and ``..`` segments.
"""

from __future__ import annotations

import hashlib
import hmac
import os
import secrets
import time
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol
from urllib.parse import quote, urlencode

import httpx
from app.errors import ValidationFailed

from core.files.s3 import S3Config, presign


def new_object_key(filename: str) -> str:
    suffix = Path(filename).suffix.lower()
    now = time.gmtime()
    return f"{now.tm_year:04d}/{now.tm_mon:02d}/{uuid.uuid4().hex}{suffix}"


@dataclass(frozen=True)
class SignedUrl:
    url: str
    expires_in: int


class Storage(Protocol):
    async def put(self, key: str, data: bytes, content_type: str) -> None: ...

    async def get(self, key: str) -> bytes: ...

    async def delete(self, key: str) -> None: ...

    def signed_url(self, key: str, *, expires_in: int | None = None) -> SignedUrl: ...

    def verify(self, key: str, expires: int, signature: str) -> None: ...


def _safe_parts(key: str) -> list[str]:
    parts = [part for part in key.split("/") if part]
    if not parts or any(part in {".", ".."} for part in parts) or key.startswith("/"):
        raise ValidationFailed(
            "The storage key is not valid",
            message_key="error.file.invalid_key",
        )
    return parts


class LocalStorage:
    """Filesystem storage used by development and the test suite."""

    def __init__(self, root: str | Path, secret: str, *, url_prefix: str = "/api/v1/files/content") -> None:
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)
        self.secret = secret.encode()
        self.url_prefix = url_prefix.rstrip("/")

    def _path(self, key: str) -> Path:
        path = self.root.joinpath(*_safe_parts(key))
        resolved = path.resolve()
        if self.root.resolve() not in resolved.parents and resolved != self.root.resolve():
            raise ValidationFailed(
                "The storage key is not valid",
                message_key="error.file.invalid_key",
            )
        return resolved

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        _ = content_type
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(f".{path.name}.{secrets.token_hex(4)}.tmp")
        temporary.write_bytes(data)
        os.replace(temporary, path)

    async def get(self, key: str) -> bytes:
        path = self._path(key)
        if not path.is_file():
            raise ValidationFailed(
                "The stored object is missing",
                message_key="error.file.missing_object",
                details={"key": key},
            )
        return path.read_bytes()

    async def delete(self, key: str) -> None:
        path = self._path(key)
        path.unlink(missing_ok=True)

    def _signature(self, key: str, expires: int) -> str:
        message = f"GET\n{key}\n{expires}".encode()
        return hmac.new(self.secret, message, hashlib.sha256).hexdigest()

    def signed_url(self, key: str, *, expires_in: int | None = None) -> SignedUrl:
        ttl = expires_in or 600
        expires = int(time.time()) + ttl
        signature = self._signature(key, expires)
        path = "/".join(quote(part) for part in _safe_parts(key))
        query = urlencode({"expires": expires, "signature": signature})
        return SignedUrl(f"{self.url_prefix}/{path}?{query}", ttl)

    def verify(self, key: str, expires: int, signature: str) -> None:
        if expires < int(time.time()):
            raise ValidationFailed(
                "This download link has expired",
                message_key="error.file.expired",
                status_code=410,
            )
        expected = self._signature(key, expires)
        if not hmac.compare_digest(expected, signature):
            raise ValidationFailed(
                "This download link is not valid",
                message_key="error.file.invalid_signature",
            )


class S3Storage:
    """S3-compatible storage with server-side presigned URLs."""

    def __init__(self, config: S3Config, *, client: httpx.AsyncClient | None = None) -> None:
        self.config = config
        self._client = client

    def _http(self) -> httpx.AsyncClient:
        if self._client is None:
            self._client = httpx.AsyncClient(timeout=30.0)
        return self._client

    def signed_url(self, key: str, *, expires_in: int | None = None) -> SignedUrl:
        ttl = expires_in or 600
        return SignedUrl(presign(self.config, "GET", key, expires_in=ttl), ttl)

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        url = presign(self.config, "PUT", key, expires_in=300)
        response = await self._http().put(url, content=data, headers={"Content-Type": content_type})
        if response.status_code >= 400:
            raise ValidationFailed(
                "The file could not be stored",
                message_key="error.file.storage_failed",
                details={"status": response.status_code},
                status_code=502,
            )

    async def get(self, key: str) -> bytes:
        url = presign(self.config, "GET", key, expires_in=300)
        response = await self._http().get(url)
        if response.status_code == 404:
            raise ValidationFailed(
                "The stored object is missing",
                message_key="error.file.missing_object",
                details={"key": key},
            )
        if response.status_code >= 400:
            raise ValidationFailed(
                "The file could not be read",
                message_key="error.file.storage_failed",
                details={"status": response.status_code},
                status_code=502,
            )
        return response.content

    async def delete(self, key: str) -> None:
        url = presign(self.config, "DELETE", key, expires_in=300)
        response = await self._http().delete(url)
        if response.status_code >= 400 and response.status_code != 404:
            raise ValidationFailed(
                "The file could not be removed",
                message_key="error.file.storage_failed",
                details={"status": response.status_code},
                status_code=502,
            )

    def verify(self, key: str, expires: int, signature: str) -> None:
        # S3 verifies its own signature; the API never accepts an unsigned URL
        # for the s3 driver because signed URLs point at the bucket directly.
        raise ValidationFailed(
            "The local content route is not used with S3 storage",
            message_key="error.file.invalid_signature",
            status_code=404,
        )

    async def close(self) -> None:
        if self._client is not None:
            await self._client.aclose()
            self._client = None


def build_storage(settings) -> Storage:  # type: ignore[no-untyped-def]
    driver = (settings.storage_driver or "local").lower()
    if driver == "local":
        base = settings.public_base_url.rstrip("/")
        return LocalStorage(
            settings.storage_dir,
            settings.secret_key,
            url_prefix=f"{base}/api/v1/files/content",
        )
    if driver == "s3":
        missing = [
            name
            for name, value in (
                ("STORAGE_S3_ENDPOINT", settings.storage_s3_endpoint),
                ("STORAGE_S3_BUCKET", settings.storage_s3_bucket),
                ("STORAGE_S3_ACCESS_KEY", settings.storage_s3_access_key),
                ("STORAGE_S3_SECRET_KEY", settings.storage_s3_secret_key),
            )
            if not value
        ]
        if missing:
            raise RuntimeError(f"S3 storage is missing {', '.join(missing)}")
        return S3Storage(
            S3Config(
                endpoint=settings.storage_s3_endpoint,
                region=settings.storage_s3_region,
                bucket=settings.storage_s3_bucket,
                access_key=settings.storage_s3_access_key,
                secret_key=settings.storage_s3_secret_key,
                path_style=settings.storage_s3_path_style,
            )
        )
    raise RuntimeError(f"Unknown STORAGE_DRIVER {settings.storage_driver!r}")


